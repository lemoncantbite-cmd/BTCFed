create extension if not exists vector;

create table if not exists public.stories (
    id uuid primary key default gen_random_uuid(),
    title text not null,
    summary text not null default '',
    type text not null check (type in ('social', 'newspaper')),
    country text not null,
    lang text not null default 'en',
    published_at timestamptz not null,
    embedding vector(384),
    sentiment_score real,
    sentiment_label text,
    sentiment_model text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.story_sources (
    id bigint generated by default as identity primary key,
    story_id uuid not null references public.stories(id) on delete cascade,
    source text not null,
    url text not null,
    url_hash text not null unique,
    title_hash text not null,
    published_at timestamptz not null,
    created_at timestamptz not null default now()
);

create index if not exists stories_embedding_cosine_idx
    on public.stories using hnsw (embedding vector_cosine_ops);
create index if not exists stories_published_at_idx
    on public.stories (published_at desc);
create index if not exists story_sources_story_id_idx
    on public.story_sources (story_id);
create index if not exists story_sources_title_hash_idx
    on public.story_sources (title_hash);

create or replace function public.match_story(q vector, threshold double precision)
returns uuid
language sql
stable
set search_path = public, extensions
as $$
    select id
    from public.stories
    where embedding is not null
      and 1 - (embedding <=> q) >= threshold
    order by embedding <=> q
    limit 1
$$;

revoke all on function public.match_story(vector, double precision)
    from public, anon, authenticated;
grant execute on function public.match_story(vector, double precision)
    to service_role;

drop view if exists public.feed cascade;

create or replace view public.feed as
select
    s.id,
    s.title,
    s.summary,
    s.type,
    s.country,
    coalesce(string_agg(distinct ss.source, ', '), 'Manual') as source,
    coalesce(
        (array_agg(ss.url order by ss.published_at desc)
            filter (where ss.url is not null))[1],
        ''
    ) as url,
    s.published_at as "publishedAt",
    greatest(1, ceil(char_length(s.summary) / 1000.0)::integer) as "readMin",
    s.sentiment_score as sentiment
from public.stories as s
left join public.story_sources as ss on ss.story_id = s.id
group by s.id;

alter table public.stories enable row level security;
alter table public.story_sources enable row level security;

revoke all on public.stories, public.story_sources from anon, authenticated;
grant select on public.feed to anon, authenticated;
grant all on public.stories, public.story_sources to service_role;
